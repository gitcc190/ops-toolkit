#!/usr/bin/env bash
# ============================================================
# common.sh —— 公共函数库
# 作用：给所有脚本提供统一的日志格式、错误退出、依赖检查
# 用法：在脚本开头 source 本文件
#   SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
#   source "$SCRIPT_DIR/lib/common.sh"
# ============================================================

# -e 出错立即退出；-u 用未定义变量报错；-o pipefail 管道中任一环失败即失败
# 注意：本文件被 source 后，这三个选项对调用脚本同样生效，这是有意为之
set -euo pipefail

# 日志级别可由环境变量覆盖，例如 LOG_LEVEL=DEBUG ./disk_alert.sh
LOG_LEVEL="${LOG_LEVEL:-INFO}"

# ------------------------------------------------------------
# 内部函数：按级别输出一行日志
# 格式固定为「YYYY-mm-dd HH:MM:SS [级别 ] 消息」，方便 grep 与后续接 ELK
# ------------------------------------------------------------
_log() {
  local level="$1"
  shift
  printf '%s [%-5s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$level" "$*"
}

log_info()  { _log INFO  "$@"; }
log_warn()  { _log WARN  "$@" >&2; }
log_error() { _log ERROR "$@" >&2; }
log_debug() {
  if [ "$LOG_LEVEL" = "DEBUG" ]; then
    _log DEBUG "$@"
  fi
}

# ------------------------------------------------------------
# die：打印错误并退出
# 退出码由第二个参数指定，默认 1
# ------------------------------------------------------------
die() {
  local msg="$1"
  local code="${2:-1}"
  log_error "$msg"
  exit "$code"
}

# ------------------------------------------------------------
# require_cmd：检查命令是否存在，缺一个就退出
# 用法：require_cmd df awk sort
# ------------------------------------------------------------
require_cmd() {
  local cmd
  for cmd in "$@"; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
      die "缺少必要命令：$cmd（Ubuntu 可执行 sudo apt install -y $cmd）" 2
    fi
  done
}

